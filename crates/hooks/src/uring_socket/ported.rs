#[test]
fn ssl_accept() {
    let (sock, addr) = listen();
    let (file, content) = jpg_file("ssl-accept");
    let fsize = content.len();
    run_pair(
        || {
            let mut conn = sock.accept().expect("accepted");
            conn.enable_ssl(true);
            assert!(conn.ssl_handshake());
            assert_eq!(conn.send(EOF_PACKET), EOF_PACKET.len().cast_signed());
            let mut rbuf = [0_u8; 1024];

            let n = conn.io(RECV, &mut rbuf);
            assert!(n > 0);
            assert_eq!(&rbuf[..n.unsigned_abs()], EOF_PACKET_2);

            let mut jpg = vec![0_u8; fsize];
            let mut nr = 0;

            while nr < fsize {
                let ret = conn.io(RECV, &mut jpg[nr..]);
                assert!(ret > 0);
                nr += ret.unsigned_abs();
            }
            assert_eq!(jpg, content);
        },
        || {
            let mut sock = Sock::of_type(libc::AF_INET, libc::SOCK_STREAM);
            sock.enable_ssl(false);
            let retval = sock.connect(&addr);
            assert!(retval);
            assert_eq!(sock.err_code(), 0);

            let mut rbuf = [0_u8; 1024];
            let n = sock.io(RECV, &mut rbuf);
            assert!(n > 0);
            assert_eq!(&rbuf[..n.unsigned_abs()], EOF_PACKET);
            assert_eq!(sock.send(EOF_PACKET_2), EOF_PACKET_2.len().cast_signed());

            let fd = unsafe { libc::open(file.as_ptr(), libc::O_RDONLY) };
            assert!(fd >= 0, "open");
            assert!(sendfile(&sock.ops, fd, 0, fsize));
            unsafe { libc::close(fd) };
        },
    );
    std::fs::remove_file(file.to_str().unwrap()).unwrap();
}

