#[test]
fn writev_and_readv() {
    let iovcnt = 3;
    let pairs = socketpair();
    let text = b"Hello World";
    let length = text.len();
    run_pair(
        || {
            let mut results = vec![vec![0_u8; length]; iovcnt];
            let mut iov: Vec<libc::iovec> = results
                .iter_mut()
                .map(|result| libc::iovec {
                    iov_base: result.as_mut_ptr().cast(),
                    iov_len: length,
                })
                .collect();

            let sock = Sock::new(pairs[1]);
            let result = sock.vector(&mut iov, false, false);
            drop(sock);
            assert_eq!(result, (length * 3).cast_signed());

            for result in &results {
                assert_eq!(result, text);
            }
        },
        || {
            let mut iov = vec![
                libc::iovec {
                    iov_base: text.as_ptr().cast_mut().cast(),
                    iov_len: length,
                };
                iovcnt
            ];
            let sock = Sock::new(pairs[0]);
            let result = sock.vector(&mut iov, true, false);
            drop(sock);
            assert_eq!(result, (length * 3).cast_signed());
        },
    );
}

